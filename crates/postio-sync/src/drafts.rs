//! Keeps the Drafts mailbox in step with the composer: append the new text, then remove the old
//! copy, never the reverse, so a failed append loses nothing.
//! `SaveDraft` carries no message; bytes are built here at drain time, which is also why queued
//! saves fold. `DiscardDraft` carries its own `RemoteId`, since the local row is gone.
//! No search: with no `UidPlus` the mailbox is flagged for resync instead of guessing which message
//! was just written.

use std::collections::BTreeSet;

use postio_account::backend::{AppendMessage, Capabilities, Capability, FlagChange, MailBackend};
use postio_model::ids::DraftId;
use postio_model::{Flag, FlagSet, MailboxId, OutgoingAttachment, RemoteId, outgoing};
use postio_storage::BlobStore;
use postio_storage::Connection;
use postio_storage::repository::{AccountRepository, DraftRepository, MailboxRepository};

use crate::drain::{Outcome, Result};

#[derive(Debug, Clone)]
pub(crate) enum DraftJob {
    Save {
        draft: DraftId,
        mailbox: MailboxId,
        path: String,
        raw: Vec<u8>,
        previous: Option<RemoteId>,
    },
    Discard {
        mailbox: MailboxId,
        path: String,
        copy: RemoteId,
    },
}

pub(crate) enum ResolvedDraft {
    Ready(Box<DraftJob>),
    Obsolete(String),
    Later(String),
    Impossible(String),
}

pub(crate) async fn resolve_save(
    connection: &Connection,
    blobs: Option<&BlobStore>,
    draft_id: DraftId,
    mailbox: MailboxId,
) -> Result<ResolvedDraft> {
    let Some(draft) = DraftRepository::new(connection).get(draft_id).await? else {
        return Ok(ResolvedDraft::Obsolete(
            "the draft is no longer in the local store".to_owned(),
        ));
    };
    let Some(folder) = MailboxRepository::new(connection).get(mailbox).await? else {
        return Ok(ResolvedDraft::Obsolete(
            "the Drafts mailbox is no longer in the local store".to_owned(),
        ));
    };

    let Some(account) = AccountRepository::new(connection)
        .get(draft.account_id)
        .await?
    else {
        return Ok(ResolvedDraft::Impossible(
            "the account is no longer in the local store".to_owned(),
        ));
    };
    let identity = draft
        .identity_id
        .and_then(|id| account.identities.iter().find(|identity| identity.id == id))
        .or_else(|| account.default_identity());
    let Some(identity) = identity else {
        return Ok(ResolvedDraft::Impossible(
            "the account has no identity to compose as".to_owned(),
        ));
    };

    let mut buffers = Vec::with_capacity(draft.attachments.len());
    for attachment in &draft.attachments {
        let Some(blob_id) = &attachment.blob_id else {
            // A wait, not a failure: the composer writes the blob off the main thread, and
            // uploading without it would leave a copy quietly missing part of itself.
            return Ok(ResolvedDraft::Later(
                "an attachment has not finished being written locally".to_owned(),
            ));
        };
        let Some(blobs) = blobs else {
            return Ok(ResolvedDraft::Impossible(
                "this drainer has no blob store to read attachments from".to_owned(),
            ));
        };
        buffers.push((attachment.clone(), blobs.get(blob_id)?));
    }
    let attachments: Vec<OutgoingAttachment<'_>> = buffers
        .iter()
        .map(|(attachment, content)| OutgoingAttachment {
            attachment,
            content,
        })
        .collect();

    // `build_draft`, not `build`: this copy reaches nobody, so it keeps the `Bcc` the outgoing
    // bytes must never carry.
    // No `in_reply_to` parent is resolved; threading headers are generated by the send.
    let built = outgoing::build_draft(&draft, identity, &attachments, None);

    Ok(ResolvedDraft::Ready(Box::new(DraftJob::Save {
        draft: draft_id,
        mailbox,
        path: folder.path,
        raw: built.raw,
        previous: server_copy(&draft),
    })))
}

/// There is no draft row left to read, so this only finds the folder. A stale id is the adapter's
/// check (#543); `run` reads it as obsolete.
pub(crate) async fn resolve_discard(
    connection: &Connection,
    mailbox: MailboxId,
    copy: RemoteId,
) -> Result<ResolvedDraft> {
    let Some(folder) = MailboxRepository::new(connection).get(mailbox).await? else {
        return Ok(ResolvedDraft::Obsolete(
            "the Drafts mailbox is no longer in the local store".to_owned(),
        ));
    };

    Ok(ResolvedDraft::Ready(Box::new(DraftJob::Discard {
        mailbox,
        path: folder.path,
        copy,
    })))
}

pub(crate) async fn run(
    connection: &Connection,
    backend: &dyn MailBackend,
    capabilities: &Capabilities,
    resync: &mut BTreeSet<i64>,
    job: &DraftJob,
) -> Outcome {
    match job {
        DraftJob::Save {
            draft,
            mailbox,
            path,
            raw,
            previous,
        } => {
            save(
                connection,
                backend,
                capabilities,
                resync,
                *draft,
                *mailbox,
                path,
                raw,
                previous.clone(),
            )
            .await
        }
        DraftJob::Discard {
            mailbox,
            path,
            copy,
        } => match remove(backend, capabilities, path, copy).await {
            Ok(Removal::Gone) => Outcome::Obsolete {
                reason: "the draft was no longer in the Drafts mailbox on the server".to_owned(),
            },
            Ok(Removal::Marked) => {
                // Marked `\Deleted` but not expunged: without UID EXPUNGE, widening could remove a
                // message another client marked. The folder is flagged instead.
                resync.insert(mailbox.get());
                Outcome::Applied
            }
            Ok(Removal::Removed) => Outcome::Applied,
            Err(error) if error.requires_full_resync() => {
                // Renumbered under the queued discard: the id names nothing now; the folder
                // reconciles by resync.
                resync.insert(mailbox.get());
                Outcome::Obsolete {
                    reason: "the Drafts mailbox has been renumbered since the draft was                              uploaded"
                        .to_owned(),
                }
            }
            Err(error) => Outcome::from_error(error),
        },
    }
}

/// `\Draft` tells other clients it is unfinished; `\Seen` because the user wrote it.
fn draft_flags() -> FlagSet {
    let mut flags = FlagSet::new();
    flags.insert(Flag::Draft);
    flags.insert(Flag::Seen);
    flags
}

#[allow(clippy::too_many_arguments)]
async fn save(
    connection: &Connection,
    backend: &dyn MailBackend,
    capabilities: &Capabilities,
    resync: &mut BTreeSet<i64>,
    draft: DraftId,
    mailbox: MailboxId,
    path: &str,
    raw: &[u8],
    previous: Option<RemoteId>,
) -> Outcome {
    let append = AppendMessage::new(raw.to_vec()).with_flags(draft_flags());
    let landed = match backend.append(path, &append).await {
        Ok(landed) => landed,
        Err(error) => {
            if error.requires_full_resync() {
                resync.insert(mailbox.get());
            }
            return Outcome::from_error(error);
        }
    };

    // Recorded before the old copy is touched: the worst failure after this is two copies, while
    // losing the id of the live copy is unrecoverable.
    let location = match &landed {
        Some(mapping) => Some(postio_storage::repository::ServerCopyLocation {
            remote_id: mapping.destination_remote_id(),
            uid: mapping.destination,
            uid_validity: mapping.uid_validity,
        }),
        // The server does not report where an append landed. Say so rather
        // than guessing: the next save cannot remove this copy, so the folder
        // is flagged and an ordinary sync pass reconciles it.
        None => {
            resync.insert(mailbox.get());
            None
        }
    };
    if let Err(error) = DraftRepository::new(connection)
        .set_server_copy(draft, location.as_ref())
        .await
    {
        // The draft was discarded mid-upload: the copy just made is orphaned, so flag the folder.
        resync.insert(mailbox.get());
        return Outcome::Obsolete {
            reason: format!("the draft went away while it was being uploaded: {error}"),
        };
    }

    let Some(previous) = previous else {
        return Outcome::Applied;
    };
    // A renumbered mailbox makes the old identity stale; the adapter knows (#543), so the removal
    // comes back as a resync answer.
    match remove(backend, capabilities, path, &previous).await {
        Ok(Removal::Removed | Removal::Gone) => Outcome::Applied,
        Ok(Removal::Marked) => {
            resync.insert(mailbox.get());
            Outcome::Applied
        }
        // The new copy is up: failing now would retry the save and upload the text twice, so flag
        // the folder.
        Err(_) => {
            resync.insert(mailbox.get());
            Outcome::Applied
        }
    }
}

pub(crate) enum Removal {
    Removed,
    Marked,
    Gone,
}

pub(crate) async fn remove(
    backend: &dyn MailBackend,
    capabilities: &Capabilities,
    path: &str,
    copy: &RemoteId,
) -> std::result::Result<Removal, postio_account::backend::BackendError> {
    let ids = std::slice::from_ref(copy);
    let mut flags = FlagSet::new();
    flags.insert(Flag::Deleted);

    let updated = backend
        .store_flags(path, ids, &FlagChange::Add(flags))
        .await?;
    if updated.is_empty() {
        return Ok(Removal::Gone);
    }

    if !capabilities.contains(Capability::UidPlus) {
        return Ok(Removal::Marked);
    }
    backend.expunge(path, Some(ids)).await?;
    Ok(Removal::Removed)
}

pub(crate) fn server_copy(draft: &postio_model::Draft) -> Option<RemoteId> {
    draft.server.remote_id.clone()
}
